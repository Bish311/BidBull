TIER_ONE_CEILING_CENTS = 4999
TIER_TWO_CEILING_CENTS = 24999
TIER_THREE_CEILING_CENTS = 99999

INCREMENT_TIER_ONE_CENTS = 100
INCREMENT_TIER_TWO_CENTS = 500
INCREMENT_TIER_THREE_CENTS = 1000
INCREMENT_TIER_FOUR_CENTS = 2500


def get_tier_increment(price_cents: int) -> int:
    if price_cents <= TIER_ONE_CEILING_CENTS:
        return INCREMENT_TIER_ONE_CENTS
    if price_cents <= TIER_TWO_CEILING_CENTS:
        return INCREMENT_TIER_TWO_CENTS
    if price_cents <= TIER_THREE_CEILING_CENTS:
        return INCREMENT_TIER_THREE_CENTS
    return INCREMENT_TIER_FOUR_CENTS
